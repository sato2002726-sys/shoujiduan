function handleChoiceSelect(choiceIdx) {
  if (isTransitioningCard) return;
  isTransitioningCard = true;

  const card = document.getElementById("active-quiz-card");
  card.classList.remove(...leanPreviewClasses);
  card.style.transform = "";

  playSynthTone("select");
  userAnswers[currentQIndex] = choiceIdx;

  // 立即高亮被点击的按钮
  const choiceBtns = document.querySelectorAll(".joker-hand-card");
  choiceBtns.forEach(btn => {
    btn.blur();
    btn.classList.remove("selected-choice");
    const idx = parseInt(btn.dataset.choice, 10);
    if (idx === choiceIdx) btn.classList.add("selected-choice");
  });

  const floatWrap = document.getElementById("quiz-float-wrapper");
  if (floatWrap) floatWrap.classList.add("is-paused");

  card.classList.remove(...moveDirectionClasses, "card-deal-in", "card-fade-out");
  setTimeout(() => {
    void card.offsetWidth;
    card.classList.add(moveDirectionClasses[choiceIdx] || "move-left-far");
  }, 110);

  // 280ms 处衔接柔和淡出，为按钮选中反馈留出短暂停顿。
  setTimeout(() => {
    card.classList.add("card-fade-out");
  }, 280);

  // 560ms 后切入下一题并从中央发牌浮现。
  setTimeout(() => {
    card.classList.remove(...moveDirectionClasses, "card-fade-out");
    isTransitioningCard = false;

    if (currentQIndex < questionsData.length - 1) {
      currentQIndex++;
      renderQuestion(currentQIndex, true);
    } else {
      computeObservationResult();
      triggerPixelWaveTransition("#E84828", () => {
        switchAct("act-result");
        renderResultStage("host");
      });
    }
  }, 560);
}

