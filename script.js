function computeObservationResult() {
  const baseScale = [2, 1, -1, -2];
  const raw = { V: 0, S: 0, E: 0, C: 0, T: 0 };

  questionsData.forEach((q, idx) => {
    const ansIdx = userAnswers[idx];
    let pts = ansIdx !== null && baseScale[ansIdx] !== undefined ? baseScale[ansIdx] * q.weight : 0;
    if (q.reverse) pts *= -1;
    raw[q.dim] += pts;
  });

  currentRawScores = raw;

  const dimOrder = ["V", "S", "E", "C", "T"];
  currentBinaryStr = dimOrder.map(d => (raw[d] > 0 ? "1" : "0")).join("");
  const original32Id = parseInt(currentBinaryStr, 2) + 1;
  currentPersonaId = persona32To12Map[original32Id] || 1;
}

