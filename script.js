let audioCtx = null;

function playSynthTone(type = "hover") {
  if (!soundEnabled) return;
  try {
    if (!audioCtx) {
      audioCtx = new (window.AudioContext || window.webkitAudioContext)();
    }
    if (audioCtx.state === "suspended") {
      audioCtx.resume().catch(() => {});
    }

    const now = audioCtx.currentTime;
    const playVoice = (wave, startHz, endHz, delay, duration, volume) => {
      const osc = audioCtx.createOscillator();
      const gain = audioCtx.createGain();
      const startAt = now + delay;
      const endAt = startAt + duration;

      osc.type = wave;
      osc.frequency.setValueAtTime(startHz, startAt);
      osc.frequency.exponentialRampToValueAtTime(endHz, endAt);
      gain.gain.setValueAtTime(0.001, startAt);
      gain.gain.exponentialRampToValueAtTime(volume, startAt + Math.min(0.012, duration / 4));
      gain.gain.exponentialRampToValueAtTime(0.001, endAt);
      osc.connect(gain);
      gain.connect(audioCtx.destination);
      osc.start(startAt);
      osc.stop(endAt + 0.01);
    };

    if (type === "hover") {
      playVoice("triangle", 520, 720, 0, 0.055, 0.025);
      playVoice("sine", 1040, 880, 0.006, 0.04, 0.008);
    } else if (type === "select") {
      playVoice("square", 440, 880, 0, 0.105, 0.025);
      playVoice("triangle", 660, 1320, 0.018, 0.075, 0.018);
      playVoice("sine", 110, 55, 0, 0.16, 0.035);
    } else if (type === "unseal") {
      playVoice("sawtooth", 180, 62, 0, 0.38, 0.025);
      playVoice("sine", 72, 38, 0, 0.48, 0.055);
      playVoice("triangle", 260, 520, 0.05, 0.28, 0.018);
    }
  } catch {
    // Audio playback may be unavailable due to browser policy or unsupported APIs.
  }
}

