// 8. 乱码解码引擎：全量解码 + 5~10s 局部伪随机字形闪烁 + 语言切换同步闪烁
// ==========================================================================
const CIPHER_GLYPHS = "紋獣観測録掌心印痕爪影壱弐参肆伍陸漆捌玖拾※◈✦";

function runCipherScramble(element, customTargetText = null, partialRatio = 1.0) {
  if (!element) return;
  const targetText =
    customTargetText !== null
      ? customTargetText
      : element.dataset[currentLang] || element.dataset.baseText || element.textContent;

  if (!targetText || targetText.length === 0) return;
  element.dataset.baseText = targetText;

  // 清除该元素上未完成的旧定时器，防止快速点击语言按钮时字符错乱
  if (element._glitchTimer) {
    clearInterval(element._glitchTimer);
    element._glitchTimer = null;
  }

  // 若为局部伪随机闪烁（partialRatio < 1），仅抽取少部分字符位置跳动
  const glitchIndices = new Set();
  if (partialRatio < 1.0) {
    const chars = targetText.split("");
    chars.forEach((ch, idx) => {
      if (ch.trim() !== "" && Math.random() < partialRatio) {
        glitchIndices.add(idx);
      }
    });
    if (glitchIndices.size === 0 && chars.length > 0) {
      glitchIndices.add(Math.floor(Math.random() * chars.length));
    }
  }

  let iter = 0;
  const step = partialRatio < 1.0 ? Math.max(0.45, targetText.length / 7) : Math.max(0.38, targetText.length / 8);

  element._glitchTimer = setInterval(() => {
    element.textContent = targetText
      .split("")
      .map((char, idx) => {
        if (char === " " || char === "\n") return char;
        if (partialRatio < 1.0 && !glitchIndices.has(idx)) {
          return char;
        }
        if (idx < iter) return targetText[idx];
        return CIPHER_GLYPHS[Math.floor(Math.random() * CIPHER_GLYPHS.length)];
      })
      .join("");

    iter += step;
    if (iter >= targetText.length) {
      element.textContent = targetText;
      clearInterval(element._glitchTimer);
      element._glitchTimer = null;
    }
  }, 40);
}

// 每隔 5~10 秒对当前屏可见的少部分重点标签触发一次伪随机字形闪烁
function triggerAmbientMicroGlitch() {
  const activeAct = document.querySelector(".act-section.active");
  if (!activeAct) return;

  const candidates = Array.from(activeAct.querySelectorAll(".glitch-target")).filter(el => {
    if (el.closest(".hidden")) return false;
    const rect = el.getBoundingClientRect();
    return rect.width > 0 && rect.height > 0 && rect.bottom > 0 && rect.top < window.innerHeight;
  });

  if (candidates.length === 0) return;

  // 每次随机抽取 1~2 个关键元素，仅扰动其中约 35% 的字符
  const pickCount = Math.min(candidates.length, Math.random() > 0.55 ? 2 : 1);
  const shuffled = candidates.sort(() => Math.random() - 0.5);

  for (let i = 0; i < pickCount; i++) {
    const targetEl = shuffled[i];
    runCipherScramble(targetEl, targetEl.textContent, 0.36);
  }
}

function startAmbientGlitchScheduler() {
  const scheduleNext = () => {
    const nextDelay = 5000 + Math.random() * 5000; // 5s ~ 10s 随机周期
    setTimeout(() => {
      triggerAmbientMicroGlitch();
      scheduleNext();
    }, nextDelay);
  };
  scheduleNext();
}

