function triggerPixelWaveTransition(colorHex = "#E84828", onMidpointCallback = null) {
  const canvas = document.getElementById("pixel-wave-canvas");
  const ctx = canvas.getContext("2d");
  const w = (canvas.width = window.innerWidth);
  const h = (canvas.height = window.innerHeight);

  const cellSize = 26;
  const cols = Math.ceil(w / cellSize);
  const rows = Math.ceil(h / cellSize);
  const totalFrames = 34;
  let frame = 0;
  let midpointTriggered = false;

  const delays = [];
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const waveOffset = Math.sin(c * 0.25) * 2.5 + (r / rows) * 8 + Math.random() * 4;
      delays.push({ c, r, delay: waveOffset });
    }
  }

  function renderFrame() {
    ctx.clearRect(0, 0, w, h);
    ctx.fillStyle = colorHex;

    const progress = frame;
    delays.forEach(cell => {
      const activeIn = progress >= cell.delay;
      const activeOut = progress >= cell.delay + 16;
      if (activeIn && !activeOut) {
        ctx.fillRect(cell.c * cellSize, cell.r * cellSize, cellSize + 1, cellSize + 1);
      }
    });

    if (frame >= 15 && !midpointTriggered) {
      midpointTriggered = true;
      if (typeof onMidpointCallback === "function") {
        onMidpointCallback();
      }
    }

    frame++;
    if (frame <= totalFrames) {
      requestAnimationFrame(renderFrame);
    } else {
      ctx.clearRect(0, 0, w, h);
    }
  }

  requestAnimationFrame(renderFrame);
}

