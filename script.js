function applyLanguage(lang) {
  document.documentElement.lang = lang;
  currentLang = lang;
  const dict = uiStrings[lang];
  document.getElementById("lang-btn-text").textContent = dict.lang_switch;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) {
      el.innerHTML = dict[key];
    }
  });

  // 首屏主标题全量解码闪烁
  runCipherScramble(document.getElementById("cipher-title"));

  // 当前可见的重点视觉标签与标题同步触发重译解码闪烁
  const activeAct = document.querySelector(".act-section.active");
  if (activeAct) {
    const scrambleSelectors =
      ".glitch-target, .paper-card-title, .beast-name, .primal-title, .info-panel-head h3, .stage-card-header h4";
    activeAct.querySelectorAll(scrambleSelectors).forEach(el => {
      if (el.id === "cipher-title" || el.closest(".hidden")) return;
      const text = el.textContent.trim();
      if (text.length > 0 && text.length <= 28) {
        runCipherScramble(el, text, 0.72);
      }
    });
  }

  renderCodexGrid();

  if (document.getElementById("act-quiz").classList.contains("active")) {
    renderQuestion(currentQIndex, false);
  }
  if (document.getElementById("act-result").classList.contains("active")) {
    renderResultStage(resultViewMode);
  }
}

