function init3DCardTilt() {
  document.querySelectorAll(".tilt-3d-card:not(#active-quiz-card)").forEach(card => {
    const updateTilt = (clientX, clientY) => {
      const rect = card.getBoundingClientRect();
      const x = (clientX - rect.left) / rect.width - 0.5;
      const y = (clientY - rect.top) / rect.height - 0.5;
      card.style.transform = `perspective(900px) rotateY(${(x * 16).toFixed(2)}deg) rotateX(${(-y * 16).toFixed(2)}deg) scale(1.02)`;
    };
    const resetTilt = () => {
      card.classList.remove("is-touch-tilting");
      card.style.transform = "";
    };

    card.addEventListener("mousemove", e => {
      updateTilt(e.clientX, e.clientY);
    });
    card.addEventListener("mouseleave", resetTilt);
    card.addEventListener("touchstart", e => {
      const touch = e.touches[0];
      if (!touch) return;
      card.classList.add("is-touch-tilting");
      updateTilt(touch.clientX, touch.clientY);
    }, { passive: true });
    card.addEventListener("touchmove", e => {
      const touch = e.touches[0];
      if (touch) updateTilt(touch.clientX, touch.clientY);
    }, { passive: true });
    card.addEventListener("touchend", resetTilt, { passive: true });
    card.addEventListener("touchcancel", resetTilt, { passive: true });
  });
}

function initArchiveScrollSync() {
  const bundles = document.querySelectorAll(".archive-card-bundle");
  const navItems = document.querySelectorAll(".sidebar-nav-item");

  navItems.forEach(item => {
    item.addEventListener("click", () => {
      const idx = parseInt(item.dataset.index, 10);
      if (bundles[idx]) {
        bundles[idx].scrollIntoView({ behavior: "smooth", block: "center" });
      }
    });
  });

  window.addEventListener(
    "scroll",
    () => {
      if (!document.getElementById("act-intro").classList.contains("active")) return;
      let activeIdx = 0;
      bundles.forEach((bundle, idx) => {
        const rect = bundle.getBoundingClientRect();
        if (rect.top < window.innerHeight * 0.52) {
          activeIdx = idx;
        }
      });
      navItems.forEach((nav, idx) => nav.classList.toggle("active", idx === activeIdx));
    },
    { passive: true }
  );
}

